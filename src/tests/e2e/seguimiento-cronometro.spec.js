test("sincroniza nombre y evento vinculado al agregar o editar desde el carril, también en móvil", async ({ page }) => {
    await page.clock.install({ time: new Date() })
    await page.goto("/")
    await page.getByRole("button", { name: "Eventos", exact: true }).click()
    await page.getByRole("button", { name: "Crear evento", exact: true }).click()
    const formEvento = page.getByRole("form", { name: "Nuevo evento" })
    await formEvento.getByLabel("Nombre").fill("Poner la mesa")
    await formEvento.getByRole("button", { name: "Guardar evento" }).click()

    await page.getByRole("button", { name: "Planificaciones", exact: true }).click()
    await page.getByRole("button", { name: /Secuencia con cronómetro/ }).click()
    const editor = page.locator(".editor-plantilla-calendario")
    await editor.getByLabel("Nombre de la plantilla").fill("Rutina del desayuno")
    let actividades = editor.locator(".editor-plantilla-actividad")
    await actividades.nth(0).getByLabel("Nombre").fill("Preparar desayuno")
    await actividades.nth(1).getByLabel("Nombre").fill("Desayunar")
    await editor.getByRole("button", { name: "Guardar plantilla" }).click()
    await page.getByLabel("Aplicar a la fecha").fill(manana())
    await page.getByLabel("Hora real de inicio Rutina del desayuno").fill("09:00:00")
    await page.getByRole("button", { name: "Aplicar a fecha" }).click()
    await page.locator(".marcador-secuencia-cronometro").click()
    const tarjeta = page.locator(".tarjeta-secuencia-cronometro")
    await tarjeta.getByRole("button", { name: "Iniciar este evento" }).first().click()

    const carril = page.getByRole("region", { name: "Carril de seguimiento", exact: true })
    let pendientes = carril.getByRole("region", { name: "Eventos pendientes del carril de seguimiento" })
    const filaDesayuno = pendientes.getByRole("listitem").filter({ hasText: "Desayunar" })
    await filaDesayuno.getByRole("button", { name: "Editar" }).click()
    let formulario = carril.getByRole("form", { name: "Editar evento pendiente" })
    await formulario.getByLabel("Evento (opcional)").selectOption({ label: "Poner la mesa" })
    const nombreVinculado = formulario.getByLabel("Nombre", { exact: true })
    await expect(nombreVinculado).toHaveValue("Poner la mesa")
    await expect(nombreVinculado).toBeDisabled()
    await formulario.getByRole("button", { name: "Guardar" }).click()

    let planes = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), CLAVE_PLANES)
    let planVinculado = planes.find(plan => plan.eventoId && plan.nombre === "Poner la mesa")
    expect(planVinculado).toBeTruthy()
    expect(planVinculado.eventoId).toBeTruthy()

    pendientes = carril.getByRole("region", { name: "Eventos pendientes del carril de seguimiento" })
    await pendientes.getByRole("listitem").filter({ hasText: "Poner la mesa" }).getByRole("button", { name: "Editar" }).click()
    formulario = carril.getByRole("form", { name: "Editar evento pendiente" })
    await formulario.getByLabel("Evento (opcional)").selectOption({ label: "Sin evento" })
    const nombreDesvinculado = formulario.getByLabel("Nombre", { exact: true })
    await expect(nombreDesvinculado).toBeEnabled()
    await expect(nombreDesvinculado).toHaveValue("Poner la mesa")
    await nombreDesvinculado.fill("Desayunar sin vínculo")
    await formulario.getByRole("button", { name: "Guardar" }).click()
    planes = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), CLAVE_PLANES)
    expect(planes.find(plan => plan.id === planVinculado.id)).toMatchObject({ nombre: "Desayunar sin vínculo", eventoId: null })

    pendientes = carril.getByRole("region", { name: "Eventos pendientes del carril de seguimiento" })
    await pendientes.getByRole("listitem").filter({ hasText: "Desayunar sin vínculo" })
        .getByRole("button", { name: "Agregar después de Desayunar sin vínculo" }).click()
    formulario = carril.getByRole("form", { name: "Agregar evento" })
    await formulario.getByLabel("Evento (opcional)").selectOption({ label: "Poner la mesa" })
    await expect(formulario.getByLabel("Nombre", { exact: true })).toHaveValue("Poner la mesa")
    await expect(formulario.getByLabel("Nombre", { exact: true })).toBeDisabled()
    await formulario.getByRole("button", { name: "Guardar" }).click()
    planes = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), CLAVE_PLANES)
    expect(planes.filter(plan => plan.eventoId).map(plan => plan.nombre)).toEqual(["Poner la mesa"])

    await page.setViewportSize({ width: 390, height: 844 })
    const botonAgregar = carril.getByRole("button", { name: /Agregar después de/ }).first()
    await expect(botonAgregar).toBeVisible()
    const caja = await botonAgregar.boundingBox()
    expect(caja.x).toBeGreaterThanOrEqual(0)
    expect(caja.x + caja.width).toBeLessThanOrEqual(390)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})

test("la etapa Focus de una secuencia conserva su acción de inicio independiente", async ({ page }) => {
    await page.clock.install({ time: new Date() })
    await page.goto("/")
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    let focus = page.getByRole("region", { name: "Focus" })
    await focus.getByLabel("Pares de bloques").selectOption("1")
    await focus.getByLabel("Concentración inicial (min)").fill("1")
    await focus.getByLabel("Descanso inicial (min)").fill("1")
    await focus.getByLabel("Nombre de la sesión").fill("Focus de prueba")
    await focus.getByRole("button", { name: "Generar bloques" }).click()
    await focus.getByRole("button", { name: "Confirmar bloques" }).click()
    await focus.getByLabel("Nombre para guardar plantilla").fill("Focus de prueba")
    await focus.getByRole("button", { name: "Guardar plantilla" }).click()

    await page.getByRole("button", { name: "Planificaciones", exact: true }).click()
    await page.getByRole("button", { name: /Secuencia con cronómetro/ }).click()
    const editor = page.locator(".editor-plantilla-calendario")
    await editor.getByLabel("Nombre de la plantilla").fill("Secuencia con pausa Focus")
    await editor.getByRole("region", { name: "Etapa 1" }).getByLabel("Tipo de evento 1").selectOption("focus")
    await expect(editor.getByRole("region", { name: "Etapa 1" }).getByLabel("Plantilla Focus 1")).toHaveValue(/.+/)
    await editor.locator(".editor-plantilla-actividad").nth(1).getByLabel("Nombre").fill("Continuar rutina")
    await editor.getByRole("button", { name: "Guardar plantilla" }).click()
    await page.getByLabel("Aplicar a la fecha").fill(manana())
    await page.getByLabel("Hora real de inicio Secuencia con pausa Focus").fill("09:00:00")
    await page.getByRole("button", { name: "Aplicar a fecha" }).click()
    await page.locator(".marcador-secuencia-cronometro").click()

    const tarjeta = page.locator(".tarjeta-secuencia-cronometro")
    await expect(tarjeta).toContainText("Sesión Focus: Focus de prueba")
    await expect(tarjeta.getByRole("button", { name: "Iniciar Focus" })).toBeVisible()
    await expect(tarjeta.getByRole("button", { name: "Iniciar este evento" })).toHaveCount(1)
    await tarjeta.getByRole("button", { name: "Iniciar Focus" }).click()

    focus = page.getByRole("region", { name: "Focus" })
    await expect(focus.getByRole("heading", { name: "Focus de prueba" })).toBeVisible()
    await expect(focus.locator(".focus-sesion-activa")).toBeVisible()
})
