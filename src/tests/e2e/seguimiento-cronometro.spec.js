import { expect, test } from "@playwright/test"

const CLAVE_PLANES = "focus.planes.v1"
const CLAVE_REGISTROS = "focus.registros.v1"

function manana() {
    const fecha = new Date()
    fecha.setDate(fecha.getDate() + 1)
    const pad = numero => String(numero).padStart(2, "0")
    return `${fecha.getFullYear()}-${pad(fecha.getMonth() + 1)}-${pad(fecha.getDate())}`
}

test("sigue una secuencia sin duraciones con cronómetros paralelos independientes y estado persistente", async ({ page }) => {
    await page.clock.install({ time: new Date() })
    await page.goto("/")
    await page.getByRole("button", { name: "Planificaciones", exact: true }).click()
    await page.getByRole("button", { name: /Secuencia con cronómetro/ }).click()

    const editor = page.locator(".editor-plantilla-calendario")
    await editor.getByLabel("Nombre de la plantilla").fill("Rutina con cronómetro")
    let actividades = editor.locator(".editor-plantilla-actividad")
    await actividades.nth(0).getByLabel("Nombre").fill("Desayunar")
    await actividades.nth(0).getByRole("button", { name: "Agregar en paralelo" }).click()
    actividades = editor.locator(".editor-plantilla-actividad")
    await actividades.nth(1).getByLabel("Nombre").fill("Ver YouTube")
    await actividades.nth(2).getByLabel("Nombre").fill("Llamar a mi abuela")
    await editor.getByRole("button", { name: "Guardar plantilla" }).click()

    await page.getByLabel("Aplicar a la fecha").fill(manana())
    await page.getByLabel("Hora real de inicio Rutina con cronómetro").fill("09:00:00")
    await expect(page.locator(".plantilla-plan-previsualizacion")).toContainText("Sin horario ni duración")
    await page.getByRole("button", { name: "Aplicar a fecha" }).click()

    const marcador = page.locator(".marcador-secuencia-cronometro")
    await expect(marcador).toContainText("Rutina con cronómetro")
    await expect(marcador).toContainText("3 actividades")
    await marcador.click()
    const tarjeta = page.locator(".tarjeta-secuencia-cronometro")
    await expect(tarjeta).toBeVisible()
    await expect(tarjeta).toContainText("inicio previsto 09:00")
    await expect(tarjeta).toContainText("Desayunar")
    await expect(tarjeta).toContainText("Ver YouTube")
    await expect(page.getByRole("group", { name: /Registros del/ }).getByRole("button", { name: /Planificado: Desayunar/ })).toHaveCount(0)

    await tarjeta.getByRole("button", { name: "Iniciar este evento" }).first().click()
    const carril = page.getByRole("region", { name: "Carril de seguimiento", exact: true })
    await expect(carril).toContainText("Desayunar")
    let pendientes = carril.getByRole("region", { name: "Eventos pendientes del carril de seguimiento" })
    await pendientes.getByRole("listitem").filter({ hasText: "Ver YouTube" }).getByRole("button", { name: "Iniciar cronómetro" }).click()
    await pendientes.getByRole("listitem").filter({ hasText: "Llamar a mi abuela" }).getByRole("button", { name: "Iniciar cronómetro" }).click()
    const activos = carril.locator('section[aria-label="Eventos registrándose en paralelo"], section[aria-label="Evento registrándose"]')
    await expect(activos.getByRole("listitem")).toHaveCount(3)
    await expect(activos).toContainText("Desayunar")
    await expect(activos).toContainText("Ver YouTube")
    await expect(activos).toContainText("Llamar a mi abuela")

    await carril.getByRole("button", { name: "Agregar próximo evento" }).click()
    let formularioNuevo = carril.getByRole("form", { name: "Agregar evento" })
    await formularioNuevo.getByLabel("Nombre", { exact: true }).fill("Lavar platos")
    await formularioNuevo.getByRole("button", { name: "Guardar" }).click()
    pendientes = carril.getByRole("region", { name: "Eventos pendientes del carril de seguimiento" })
    await pendientes.getByRole("listitem").filter({ hasText: "Lavar platos" }).getByRole("button", { name: "Agregar después de Lavar platos" }).click()
    formularioNuevo = carril.getByRole("form", { name: "Agregar evento" })
    await formularioNuevo.getByLabel("Nombre", { exact: true }).fill("Preparar café")
    await formularioNuevo.getByRole("button", { name: "Guardar" }).click()
    const filaCafe = pendientes.getByRole("listitem").filter({ hasText: "Preparar café" })
    await filaCafe.getByRole("button", { name: "Mover Preparar café antes" }).click()
    const filaPlatos = pendientes.getByRole("listitem").filter({ hasText: "Lavar platos" })
    await filaPlatos.getByRole("button", { name: "Editar" }).click()
    const formularioEditar = carril.getByRole("form", { name: "Editar evento pendiente" })
    await formularioEditar.getByLabel("Nombre", { exact: true }).fill("Lavar los platos")
    await formularioEditar.getByRole("button", { name: "Guardar" }).click()
    await expect(pendientes.getByRole("listitem").nth(0)).toContainText("Preparar café")
    await expect(pendientes.getByRole("listitem").nth(1)).toContainText("Lavar los platos")
    page.once("dialog", dialog => dialog.accept())
    await pendientes.getByRole("listitem").filter({ hasText: "Preparar café" }).getByRole("button", { name: "Eliminar del calendario" }).click()
    await expect(pendientes.getByRole("listitem").filter({ hasText: "Preparar café" })).toHaveCount(0)
    await pendientes.getByRole("listitem").filter({ hasText: "Lavar los platos" })
        .getByRole("button", { name: "Agregar después de Lavar los platos" }).click()
    formularioNuevo = carril.getByRole("form", { name: "Agregar evento" })
    await formularioNuevo.getByLabel("Nombre", { exact: true }).fill("Comprar leche")
    await formularioNuevo.getByRole("button", { name: "Guardar" }).click()
    await pendientes.getByRole("listitem").filter({ hasText: "Comprar leche" })
        .getByRole("button", { name: "Omitir Comprar leche de esta sesión" }).click()
    await expect(carril).toContainText("Omitidos en esta sesión: Comprar leche")
    expect((await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), CLAVE_PLANES))
        .some(plan => plan.nombre === "Comprar leche")).toBe(true)
    await pendientes.getByRole("listitem").filter({ hasText: "Lavar los platos" }).getByRole("button", { name: "Iniciar cronómetro" }).click()
    await expect(activos.getByRole("listitem")).toHaveCount(4)

    await page.clock.fastForward(1200)
    await page.reload()
    const carrilRecargado = page.getByRole("region", { name: "Carril de seguimiento", exact: true })
    const activosRecargados = carrilRecargado.locator('section[aria-label="Eventos registrándose en paralelo"], section[aria-label="Evento registrándose"]')
    await expect(activosRecargados.getByRole("listitem")).toHaveCount(4)
    await activosRecargados.getByRole("listitem").filter({ hasText: "Llamar a mi abuela" }).getByRole("button", { name: /Finalizar/ }).click()

    let registros = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), CLAVE_REGISTROS)
    expect(registros.find(registro => registro.nombre === "Llamar a mi abuela").estado).toBe("Finalizado")
    expect(registros.filter(registro => ["Desayunar", "Ver YouTube", "Lavar los platos"].includes(registro.nombre)).every(registro => registro.estado === "En curso")).toBe(true)
    await expect(activosRecargados.getByRole("listitem")).toHaveCount(3)

    await activosRecargados.getByRole("listitem").filter({ hasText: "Desayunar" }).getByRole("button", { name: /Finalizar/ }).click()
    await activosRecargados.getByRole("listitem").filter({ hasText: "Ver YouTube" }).getByRole("button", { name: /Finalizar/ }).click()
    await activosRecargados.getByRole("listitem").filter({ hasText: "Lavar los platos" }).getByRole("button", { name: /Finalizar/ }).click()
    await expect(carrilRecargado).toHaveCount(0)
    registros = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), CLAVE_REGISTROS)
    expect(registros).toHaveLength(4)
    expect(registros.every(registro => registro.estado === "Finalizado" && registro.planId)).toBe(true)
    const planes = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), CLAVE_PLANES)
    expect(planes).toHaveLength(5)
    expect(planes.every(plan => plan.modoSeguimientoPlanificacion === "cronometro" && plan.fin === null)).toBe(true)
})

