import { expect, test } from "@playwright/test"

async function prepararSesion(page, pares = "2") {
    await page.clock.install({ time: new Date(2026, 9, 23, 15, 0, 0) })
    await page.goto("/")
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    const vista = page.getByRole("region", { name: "Focus" })
    await vista.getByLabel("Pares de bloques").selectOption(pares)
    await vista.getByLabel("Concentración inicial (min)").fill("1")
    await vista.getByLabel("Descanso inicial (min)").fill("1")
    await vista.getByRole("button", { name: "Generar bloques" }).click()
    await vista.getByRole("button", { name: "Confirmar bloques" }).click()
    await vista.getByRole("button", { name: "Iniciar sesión Focus" }).click()
    return vista
}

test("bloquea actividad independiente en concentración, la permite en descanso y espera antes de la siguiente concentración", async ({ page }) => {
    const vista = await prepararSesion(page)
    const controles = vista.locator(".focus-iniciar-independiente")
    const nombre = controles.getByLabel("Nombre del temporizador")
    const iniciar = controles.getByRole("button", { name: "Iniciar", exact: true })

    await expect(iniciar).toBeDisabled()
    await page.getByRole("button", { name: "Calendario", exact: true }).click()
    await page.getByLabel("Nombre del temporizador").fill("Actividad durante concentración")
    await page.getByRole("button", { name: "Iniciar", exact: true }).click()
    await expect(page.getByRole("alert")).toContainText("No se puede iniciar otra actividad mientras Focus está en concentración")
    await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("focus.registros.v1") ?? "[]")
        .some(registro => registro.nombre === "Actividad durante concentración"))).toBe(false)
    await page.getByRole("button", { name: "Focus", exact: true }).click()

    await page.clock.runFor(60_500)
    const sesion = vista.locator(".focus-sesion-activa")
    await expect(sesion.getByText("Descanso 1", { exact: true }).first()).toBeVisible()
    await expect(iniciar).toBeEnabled()

    await nombre.fill("Preparar mesa")
    await iniciar.click()
    const actividad = vista.getByRole("article", { name: "Actividad activa: Preparar mesa" })
    await expect(actividad.getByText("Estado actual: En curso")).toBeVisible()
    await page.clock.runFor(3_500)
    await sesion.getByRole("button", { name: "Continuar con concentración" }).click()
    await expect(sesion.getByText("Concentración en espera")).toBeVisible()
    await expect(actividad.getByText("Estado actual: En curso")).toBeVisible()

    await actividad.getByRole("button", { name: "Pausar" }).click()
    await expect(actividad.getByText("Estado actual: Pausado")).toBeVisible()
    await expect(sesion.getByText("Concentración 2", { exact: true }).first()).toBeVisible()
    await expect(sesion.getByText("Concentración en espera")).toHaveCount(0)
    await page.clock.runFor(3_500)
    await actividad.getByRole("button", { name: "Continuar" }).click()
    await expect(page.getByRole("alert")).toContainText("No se puede reanudar esta actividad mientras Focus está en concentración")
    await expect(actividad.getByText("Estado actual: Pausado")).toBeVisible()
    const almacenados = await page.evaluate(() => JSON.parse(localStorage.getItem("focus.registros.v1")))
    const registroActividad = almacenados.find(registro => registro.nombre === "Preparar mesa")
    const registrosFocus = almacenados.filter(registro => registro.origenFocus === true)
    const tramoActivoAnterior = registroActividad.segmentos.at(-2)
    const tramoPausa = registroActividad.segmentos.at(-1)
    expect(tramoActivoAnterior.fin).toBeTruthy()
    expect(tramoPausa.tipo).toBe("Pausado")
    expect(registrosFocus.length).toBeGreaterThan(0)
    expect(almacenados.filter(registro => registro.estado === "En curso")).toHaveLength(1)

    await page.clock.runFor(60_500)
    await expect(sesion.getByText("Descanso 2", { exact: true }).first()).toBeVisible()
    await expect(iniciar).toBeEnabled()
    await actividad.getByRole("button", { name: "Continuar" }).click()
    await expect(actividad.getByText("Estado actual: En curso")).toBeVisible()
})

test("al iniciar Focus con una actividad ya en curso, espera hasta que se pause", async ({ page }) => {
    await page.clock.install({ time: new Date(2026, 9, 23, 16, 0, 0) })
    await page.goto("/")
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    const vista = page.getByRole("region", { name: "Focus" })
    const controles = vista.locator(".focus-iniciar-independiente")
    await controles.getByLabel("Nombre del temporizador").fill("Lavar taza")
    await controles.getByRole("button", { name: "Iniciar", exact: true }).click()
    await page.clock.runFor(3_500)

    await vista.getByLabel("Pares de bloques").selectOption("1")
    await vista.getByLabel("Concentración inicial (min)").fill("1")
    await vista.getByLabel("Descanso inicial (min)").fill("1")
    await vista.getByRole("button", { name: "Generar bloques" }).click()
    await vista.getByRole("button", { name: "Confirmar bloques" }).click()
    await vista.getByRole("button", { name: "Iniciar sesión Focus" }).click()
    const sesion = vista.locator(".focus-sesion-activa")
    await expect(sesion.getByText("Concentración en espera")).toBeVisible()
    const actividad = vista.getByRole("article", { name: "Actividad activa: Lavar taza" })
    await actividad.getByRole("button", { name: "Pausar" }).click()
    await expect(sesion.getByText("Concentración 1", { exact: true }).first()).toBeVisible()
    await expect(sesion.getByText("Concentración en espera")).toHaveCount(0)
    await page.clock.runFor(3_500)
    const guardados = await page.evaluate(() => JSON.parse(localStorage.getItem("focus.registros.v1")))
    expect(guardados.filter(registro => registro.origenFocus === true)).toHaveLength(1)
    expect(guardados.filter(registro => registro.estado === "En curso")).toHaveLength(1)
})

