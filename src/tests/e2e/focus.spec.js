import { expect, test } from "@playwright/test"

const claveRegistros = "focus.registros.v1"

test("Flujo de usuario: Focus inicia actividades, mantiene varias y conserva sus controles tras recargar", async ({ page }) => {
    const inicio = new Date(2026, 9, 13, 15, 0, 0)
    await page.clock.install({ time: inicio })
    await page.goto("/")
    await page.getByRole("button", { name: "Focus", exact: true }).click()

    const vista = page.getByRole("region", { name: "Focus" })
    await expect(page.locator(".calendario-panel")).toBeHidden()
    await expect(vista.getByText("No hay actividades activas")).toBeVisible()
    await vista.getByRole("button", { name: "Iniciar", exact: true }).click()
    await expect(vista.getByRole("alert")).toContainText("Escribí un nombre para iniciar el registro")

    const nombre = vista.getByLabel("Nombre del temporizador")
    await nombre.fill("Leer")
    await vista.getByRole("button", { name: "Iniciar", exact: true }).click()
    const lectura = vista.getByRole("article", { name: "Actividad activa: Leer" })
    await expect(lectura.getByText("Estado actual: En curso")).toBeVisible()
    await page.clock.runFor(1000)
    await lectura.getByRole("button", { name: "Pausar" }).click()
    await expect(lectura.getByText("Estado actual: Pausado")).toBeVisible()

    await nombre.fill("Caminar")
    await vista.getByRole("button", { name: "Iniciar", exact: true }).click()
    const caminata = vista.getByRole("article", { name: "Actividad activa: Caminar" })
    await expect(caminata.getByText("Estado actual: En curso")).toBeVisible()
    await expect(vista.getByRole("region", { name: "En curso o en pausa · 2" })).toBeVisible()
    await page.clock.runFor(1000)

    await page.setViewportSize({ width: 390, height: 844 })
    await expect(page.locator("html")).toHaveAttribute("data-tema", "oscuro")
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole("button", { name: "Cambiar a tema claro" }).click()
    await expect(page.locator("html")).toHaveAttribute("data-tema", "claro")
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

    await page.reload()
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    const vistaRecargada = page.getByRole("region", { name: "Focus" })
    const lecturaRecargada = vistaRecargada.getByRole("article", { name: "Actividad activa: Leer" })
    const caminataRecargada = vistaRecargada.getByRole("article", { name: "Actividad activa: Caminar" })
    await expect(lecturaRecargada.getByText("Estado actual: Pausado")).toBeVisible()
    await expect(caminataRecargada.getByText("Estado actual: En curso")).toBeVisible()

    await lecturaRecargada.getByRole("button", { name: "Continuar" }).click()
    await page.clock.runFor(1000)
    await lecturaRecargada.getByRole("button", { name: "Finalizar" }).click()
    await caminataRecargada.getByRole("button", { name: "Finalizar" }).click()
    await expect(vistaRecargada.getByText("No hay actividades activas")).toBeVisible()
    const guardados = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveRegistros)
    expect(guardados).toHaveLength(2)
    expect(guardados.every(registro => registro.estado === "Finalizado")).toBe(true)
})

test("Flujo de usuario: configura bloques Focus, espera confirmación, pausa solo su registro y guarda el historial", async ({ page }) => {
    await page.clock.install({ time: new Date(2026, 9, 18, 15, 0, 0) })
    await page.goto("/")
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    const vista = page.getByRole("region", { name: "Focus" })

    await vista.getByLabel("Pares de bloques").selectOption("2")
    await vista.getByLabel("Concentración inicial (min)").fill("1")
    await vista.getByLabel("Descanso inicial (min)").fill("1")
    await vista.getByRole("button", { name: "Generar bloques" }).click()
    await vista.getByRole("button", { name: "Confirmar bloques" }).click()
    await vista.getByRole("button", { name: "Iniciar sesión Focus" }).click()
    await expect(vista.getByRole("heading", { name: "Sesión Focus" })).toBeVisible()
    const sesionActiva = vista.locator(".focus-sesion-activa")
    await expect(sesionActiva.getByText("Concentración 1", { exact: true }).first()).toBeVisible()

    await page.clock.runFor(60_500)
    await expect(sesionActiva.getByText("Descanso 1", { exact: true }).first()).toBeVisible()
    await page.clock.runFor(60_500)
    await expect(vista.getByRole("button", { name: "Confirmar inicio del bloque siguiente" })).toBeVisible()
    const temporizadorSesion = sesionActiva.locator(".focus-temporizador strong")
    await vista.getByRole("button", { name: "Pausar sesión" }).click()
    const tiempoMuertoPausado = await temporizadorSesion.textContent()
    await page.clock.runFor(30_000)
    await expect(temporizadorSesion).toHaveText(tiempoMuertoPausado)
    await vista.getByRole("button", { name: "Reanudar sesión" }).click()
    await page.clock.runFor(1_000)
    await expect(vista.getByRole("button", { name: "Confirmar inicio del bloque siguiente" })).toBeVisible()
    await vista.getByRole("button", { name: "Confirmar inicio del bloque siguiente" }).click()
    await expect(sesionActiva.getByText("Concentración 2", { exact: true }).first()).toBeVisible()

    await page.getByRole("button", { name: "Calendario", exact: true }).click()
    const nombreRegistro = page.getByLabel("Nombre del temporizador")
    await nombreRegistro.fill("Actividad paralela")
    await page.getByRole("button", { name: "Iniciar", exact: true }).click()
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    const actividadParalela = vista.getByRole("article", { name: "Actividad activa: Actividad paralela" })
    await expect(actividadParalela.getByText("Estado actual: En curso")).toBeVisible()

    await vista.getByRole("button", { name: "Pausar sesión" }).click()
    await expect(vista.getByText("Estado actual: En curso")).toBeVisible()
    await page.clock.runFor(30_000)
    await expect(vista.getByRole("button", { name: "Reanudar sesión" })).toBeVisible()
    await expect(actividadParalela.getByText("Estado actual: En curso")).toBeVisible()
    await vista.getByRole("button", { name: "Reanudar sesión" }).click()
    await page.clock.runFor(60_500)
    await expect(sesionActiva.getByText("Descanso 2", { exact: true }).first()).toBeVisible()
    await page.clock.runFor(60_500)

    await expect(vista.getByRole("heading", { name: "Sesiones guardadas" })).toBeVisible()
    await expect(vista.getByText("Sesión Focus", { exact: true })).toBeVisible()
    await expect(vista.getByRole("article", { name: "Actividad activa: Actividad paralela" }).getByText("Estado actual: En curso")).toBeVisible()
    const registros = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveRegistros)
    expect(registros).toHaveLength(2)
    expect(registros.find(registro => registro.nombre === "Sesión Focus").estado).toBe("Finalizado")
    expect(registros.find(registro => registro.nombre === "Actividad paralela").estado).toBe("En curso")
    const historialFocus = await page.evaluate(() => JSON.parse(localStorage.getItem("focus.historial-sesion.v1")))
    expect(historialFocus[0].extras.some(extra => extra.tipo === "tiempo-muerto")).toBe(true)
    expect(historialFocus[0].extras.some(extra => extra.tipo === "pausa-sesion")).toBe(true)

    await vista.getByRole("article", { name: "Actividad activa: Actividad paralela" }).getByRole("button", { name: "Finalizar" }).click()
})

test("Flujo de usuario: conserva plantillas y recupera el bloque y tiempo restante después de recargar", async ({ page }) => {
    await page.clock.install({ time: new Date(2026, 9, 18, 16, 0, 0) })
    await page.goto("/")
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    let vista = page.getByRole("region", { name: "Focus" })

    await vista.getByLabel("Pares de bloques").selectOption("1")
    await vista.getByLabel("Concentración inicial (min)").fill("1")
    await vista.getByLabel("Descanso inicial (min)").fill("1")
    await vista.getByRole("button", { name: "Generar bloques" }).click()
    await vista.getByRole("button", { name: "Confirmar bloques" }).click()
    await vista.getByLabel("Nombre para guardar plantilla").fill("Sesión corta QA")
    await vista.getByRole("button", { name: "Guardar plantilla" }).click()
    await expect(vista.getByRole("heading", { name: "Plantillas de sesión" })).toBeVisible()

    await page.reload()
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    vista = page.getByRole("region", { name: "Focus" })
    const plantilla = vista.getByRole("list").filter({ hasText: "Sesión corta QA" })
    await expect(plantilla).toBeVisible()
    await plantilla.getByRole("button", { name: "Cargar" }).click()
    await vista.getByRole("button", { name: "Confirmar bloques" }).click()
    await vista.getByRole("button", { name: "Iniciar sesión Focus" }).click()

    await page.clock.runFor(15_000)
    await page.reload()
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    vista = page.getByRole("region", { name: "Focus" })
    const sesionActiva = vista.locator(".focus-sesion-activa")
    await expect(sesionActiva.getByRole("heading", { name: "Sesión Focus" })).toBeVisible()
    await expect(sesionActiva.getByText("Concentración 1", { exact: true }).first()).toBeVisible()
    await expect(sesionActiva.getByText("00:45", { exact: true })).toBeVisible()

    await page.clock.runFor(45_500)
    await expect(sesionActiva.getByText("Descanso 1", { exact: true }).first()).toBeVisible()
    await sesionActiva.getByRole("button", { name: "Finalizar sesión" }).click()
    await expect(vista.getByRole("heading", { name: "Sesiones guardadas" })).toBeVisible()

    const plantillas = await page.evaluate(() => JSON.parse(localStorage.getItem("focus.plantillas-sesion.v1")))
    const sesiones = await page.evaluate(() => JSON.parse(localStorage.getItem("focus.historial-sesion.v1")))
    expect(plantillas).toHaveLength(1)
    expect(plantillas[0].nombrePlantilla).toBe("Sesión corta QA")
    expect(sesiones).toHaveLength(1)
    expect(sesiones[0].bloques[0].fin).not.toBeNull()
})

test("Flujo de usuario: reconcilia varios bloques vencidos y conserva los límites reales al volver a la pestaña", async ({ page }) => {
    await page.clock.install({ time: new Date(2026, 9, 18, 17, 0, 0) })
    await page.goto("/")
    await page.getByRole("button", { name: "Focus", exact: true }).click()
    const vista = page.getByRole("region", { name: "Focus" })
    await vista.getByLabel("Pares de bloques").selectOption("2")
    await vista.getByLabel("Concentración inicial (min)").fill("1")
    await vista.getByLabel("Descanso inicial (min)").fill("1")
    await vista.getByLabel("Avanzar automáticamente después de cada descanso").check()
    await vista.getByRole("button", { name: "Generar bloques" }).click()
    await vista.getByRole("button", { name: "Confirmar bloques" }).click()
    await vista.getByRole("button", { name: "Iniciar sesión Focus" }).click()

    await page.clock.fastForward(120_000)
    const sesionActiva = vista.locator(".focus-sesion-activa")
    await expect(sesionActiva.getByText("Concentración 2", { exact: true }).first()).toBeVisible()
    const registros = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveRegistros)
    const registroFocus = registros.find(registro => registro.nombre === "Sesión Focus")
    const inicioRegistro = new Date(registroFocus.segmentos[0].inicio).getTime()
    expect(registroFocus.segmentos.map(segmento => segmento.tipo)).toEqual(["En curso", "Pausado", "En curso"])
    expect(registroFocus.segmentos[0].fin).toBe(new Date(inicioRegistro + 60_000).toISOString())
    expect(registroFocus.segmentos[1].fin).toBe(new Date(inicioRegistro + 120_000).toISOString())

    await vista.getByRole("button", { name: "Finalizar sesión" }).click()
    await expect(vista.getByRole("heading", { name: "Sesiones guardadas" })).toBeVisible()
})
