    guardados = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), clavePlanes)
    expect(guardados[0].inicio).toBe(new Date(inicio.getTime() + 2000).toISOString())
    expect(guardados[0].fin).toBe(new Date(fin.getTime() + 3000).toISOString())

    const acercar = zoom.getByRole("button", { name: "Acercar calendario" })
    while (await acercar.isEnabled()) await acercar.click()
