    await page.getByLabel("Ir a fecha").fill(formatoFecha(lunesAnterior))
    await page.getByRole("button", { name: "Semana", exact: true }).click()
    await page.getByLabel("Ir a fecha").fill(formatoFecha(diaOrigen))
    await page.getByRole("button", { name: "Planificar actividad", exact: true }).click()

    const formulario = page.getByRole("form", { name: "Planificar actividad" })
    await expect(formulario.getByLabel("Inicio")).toHaveValue(isoHora(inicio))
    await formulario.getByLabel("Nombre de la actividad").fill("Plan semanal movible")
    await formulario.getByRole("button", { name: "Guardar plan", exact: true }).click()

    const grupoSemana = page.getByRole("group", { name: "Actividades de la semana" })
    const bloque = grupoSemana.getByRole("button", { name: /Planificado: Plan semanal movible/ })
    await expect(bloque).toBeVisible()
    expect(await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)).length, clavePlanes)).toBe(1)

    await page.getByRole("button", { name: "Edición directa: desactivada" }).click()
    const columnaDestino = page.locator(`.columna-registros-semana[data-fecha="${formatoFecha(diaDestino)}"]`)
    await bloque.scrollIntoViewIfNeeded()
    await columnaDestino.scrollIntoViewIfNeeded()
    const cajaBloque = await bloque.boundingBox()
    const cajaDestino = await columnaDestino.boundingBox()
    const xInicio = cajaBloque.x + cajaBloque.width / 2
    const y = cajaBloque.y + cajaBloque.height / 2
    await page.mouse.move(xInicio, y)
    await page.mouse.down()
    await page.mouse.move(cajaDestino.x + cajaDestino.width / 2, y, { steps: 8 })
    await page.mouse.up()

    const planes = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), clavePlanes)
    const inicioMovido = new Date(inicio)
    inicioMovido.setDate(inicioMovido.getDate() + 1)
    const finMovido = new Date(fin)
    finMovido.setDate(finMovido.getDate() + 1)
    expect(planes[0].inicio).toBe(inicioMovido.toISOString())
    expect(planes[0].fin).toBe(finMovido.toISOString())
    const columnaOrigen = page.locator(`.columna-registros-semana[data-fecha="${formatoFecha(diaOrigen)}"]`)
    await expect(columnaOrigen.getByRole("button", { name: /Planificado: Plan semanal movible/ })).toHaveCount(0)
    await expect(columnaDestino.getByRole("button", { name: /Planificado: Plan semanal movible/ })).toBeVisible()
    await expect(page.locator(".mensaje-ajuste-calendario[role=status]")).toContainText("Planificación movida en el calendario")

    const bloqueDestino = columnaDestino.getByRole("button", { name: /Planificado: Plan semanal movible/ })
    await bloqueDestino.focus()
    await page.keyboard.press("Shift+ArrowDown")
    const finAjustado = new Date(finMovido.getTime() + 60_000)
    const planRedimensionado = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), clavePlanes)
    expect(planRedimensionado[0].inicio).toBe(inicioMovido.toISOString())
    expect(planRedimensionado[0].fin).toBe(finAjustado.toISOString())

    await page.keyboard.press("Alt+ArrowRight")
    const movidoConTeclado = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), clavePlanes)
    const diaSiguiente = new Date(diaDestino)
    diaSiguiente.setDate(diaSiguiente.getDate() + 1)
    const inicioEsperado = new Date(diaSiguiente)
    inicioEsperado.setHours(9, 0, 0, 0)
    expect(movidoConTeclado[0].inicio).toBe(inicioEsperado.toISOString())
    expect(movidoConTeclado[0].fin).toBe(new Date(inicioEsperado.getTime() + 31 * 60_000).toISOString())

    const columnaTeclado = page.locator(`.columna-registros-semana[data-fecha="${formatoFecha(diaSiguiente)}"]`)
    await columnaTeclado.getByRole("button", { name: /Planificado: Plan semanal movible/ }).click()
    const detalle = page.getByRole("region", { name: "Plan: Plan semanal movible" })
    await expect(detalle).toBeVisible()
