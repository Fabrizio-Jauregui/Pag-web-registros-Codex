    expect((await bloque.boundingBox()).height).toBeGreaterThan(20)
    await page.getByRole("button", { name: "Edición directa: desactivada" }).click()
    const etiquetaAntes = await bloque.getAttribute("aria-label")
    await bloque.focus()
    await page.keyboard.press("ArrowDown")
    await expect.poll(() => bloque.getAttribute("aria-label")).not.toBe(etiquetaAntes)

    async function arrastrar(localizador, deltaY) {
        await localizador.scrollIntoViewIfNeeded()
        const caja = await localizador.boundingBox()
        const x = caja.x + caja.width / 2
        const y = caja.y + caja.height / 2
        await page.mouse.move(x, y)
        await page.mouse.down()
        await page.mouse.move(x, y + deltaY, { steps: 4 })
        await page.mouse.up()
    }

    await arrastrar(bloque, 10)
    let guardados = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), clavePlanes)
    expect(guardados[0].inicio).toBe(new Date(inicio.getTime() + 2000).toISOString())
    expect(guardados[0].fin).toBe(new Date(fin.getTime() + 2000).toISOString())
