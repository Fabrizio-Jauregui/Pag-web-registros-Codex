import { expect, test } from "@playwright/test"

test("Flujo de usuario: mantiene navegación y controles utilizables con teclado en una ventana estrecha", async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto("/")

    const semana = page.getByRole("button", { name: "Semana", exact: true })
    await semana.focus()
    await page.keyboard.press("Enter")
    await expect(semana).toHaveAttribute("aria-pressed", "true")
    await expect(page.getByLabel(/^Agenda de la semana:/)).toBeVisible()
    await expect(page.getByRole("table", { name: /^Semana del/ })).toBeHidden()
    await expect(page.locator(".agenda-semana-dia")).toHaveCount(7)
    await expect(page.getByRole("group", { name: "Vista y fecha" })).toBeVisible()
    await expect(page.getByRole("group", { name: "Acciones principales" })).toBeVisible()
    await expect(page.getByRole("group", { name: "Herramientas del calendario" })).toBeVisible()
    await expect(page.getByRole("group", { name: "Acciones principales" })
        .getByRole("button", { name: "Planificar actividad" })).toBeVisible()
    await expect(page.getByRole("group", { name: "Formato semanal" })
        .getByRole("button", { name: "Agenda" })).toHaveAttribute("aria-pressed", "true")
    await page.getByRole("button", { name: "Grilla por horas" }).click()
    await expect(page.getByRole("table", { name: /^Semana del/ })).toBeVisible()
    await page.getByRole("button", { name: "Agenda", exact: true }).click()
    await expect(page.getByRole("table", { name: /^Semana del/ })).toBeHidden()

    const dia = page.getByRole("button", { name: "Día", exact: true })
    await dia.focus()
    await page.keyboard.press("Enter")
    await expect(dia).toHaveAttribute("aria-pressed", "true")
    await page.getByRole("button", { name: "Acercar calendario" }).focus()
    await page.keyboard.press("Enter")
    await expect(page.locator(".controles-zoom output")).toHaveText("16 h")

    const desbordeHorizontal = await page.evaluate(() => (
        document.documentElement.scrollWidth > window.innerWidth
    ))
    expect(desbordeHorizontal).toBe(false)

    await page.getByRole("button", { name: "Eventos", exact: true }).click()
    await expect(page.getByRole("button", { name: "Crear evento", exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test("Flujo de usuario: consulta una actividad de la semana en la agenda móvil y abre su detalle", async ({ page }) => {
    const ayer = new Date()
    ayer.setDate(ayer.getDate() - 1)
    const pad = valor => String(valor).padStart(2, "0")
    const fecha = `${ayer.getFullYear()}-${pad(ayer.getMonth() + 1)}-${pad(ayer.getDate())}`
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto("/")
    await page.getByLabel("Ir a fecha").fill(fecha)
    await page.getByRole("button", { name: "Nuevo registro", exact: true }).click()
    await page.getByLabel("Nombre de la actividad").fill("Lectura de prueba móvil")
    await page.getByLabel("Inicio").fill(`${fecha}T09:00`)
    await page.getByLabel("Fin", { exact: true }).fill(`${fecha}T09:30`)
    await page.getByRole("button", { name: "Crear registro", exact: true }).click()
    await page.getByRole("button", { name: "Semana", exact: true }).click()

    const agenda = page.getByLabel(/^Agenda de la semana:/)
    const actividad = agenda.getByRole("button", { name: /Lectura de prueba móvil, En curso, 09:00 a 09:30/ })
    await expect(actividad).toBeVisible()
    await actividad.click()
    const detalle = page.getByRole("region", { name: "Lectura de prueba móvil" })
    await expect(detalle).toBeVisible()
    await detalle.getByRole("button", { name: "Cerrar detalle" }).click()
    await page.getByRole("button", { name: "Grilla por horas" }).click()
    await page.getByRole("button", { name: "Edición directa: desactivada" }).click()
    const bloque = page.getByRole("button", { name: /Lectura de prueba móvil, .*En curso, 09:00 a 09:30/ })
    await bloque.scrollIntoViewIfNeeded()
    const caja = await bloque.boundingBox()
    await page.mouse.move(caja.x + caja.width / 2, caja.y + caja.height / 2)
    await page.mouse.down()
    await page.mouse.move(caja.x + caja.width / 2, caja.y + caja.height / 2 + 16, { steps: 4 })
    await page.mouse.up()
    await expect(page.getByRole("button", { name: /Lectura de prueba móvil, .*En curso, 09:15 a 09:45/ }))
        .toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
