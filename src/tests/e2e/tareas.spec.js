test("permite crear tareas anidadas en varios niveles y conserva las rutas al recargar", async ({ page }) => {
    await page.goto("/")
    await page.getByRole("button", { name: "Tareas", exact: true }).click()
    await page.getByRole("button", { name: "Crear objetivo" }).click()
    await page.getByLabel("Nombre del objetivo").fill("Proyecto personal")
    await page.getByRole("button", { name: "Guardar objetivo" }).click()
    const objetivo = (await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)).find(item => item.tipo === "objetivo")
    const grupoCreado = page.locator(".objetivo-grupo").filter({ has: page.getByRole("heading", { name: "Proyecto personal" }) })
    await grupoCreado.getByRole("button", { name: "Editar objetivo" }).click()
    await page.getByLabel("Nombre del objetivo").fill("Proyecto personal actualizado")
    await page.getByRole("button", { name: "Guardar cambios del objetivo" }).click()

    await page.getByRole("button", { name: "Crear tarea" }).click()
    await page.getByLabel("Nombre", { exact: true }).fill("Terminar historial")
    await page.getByLabel("Dentro de").selectOption(objetivo.id)
    await page.getByRole("button", { name: "Guardar tarea" }).click()
    let guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    const padre = guardadas.find(item => item.nombre === "Terminar historial")

    await page.getByRole("button", { name: "Crear tarea" }).click()
    await page.getByLabel("Nombre", { exact: true }).fill("Editar registros")
    await page.getByLabel("Dentro de").selectOption(padre.id)
    await page.getByRole("button", { name: "Guardar tarea" }).click()
    guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    const hija = guardadas.find(item => item.nombre === "Editar registros")

    await page.getByRole("button", { name: "Crear tarea" }).click()
    await page.getByLabel("Nombre", { exact: true }).fill("Revisar borrado")
    await page.getByLabel("Dentro de").selectOption(hija.id)
    await page.getByRole("button", { name: "Guardar tarea" }).click()
    guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    const nieta = guardadas.find(item => item.nombre === "Revisar borrado")
    expect([padre.padreId, hija.padreId, nieta.padreId]).toEqual([objetivo.id, padre.id, hija.id])
    expect([padre.objetivoId, hija.objetivoId, nieta.objetivoId]).toEqual([objetivo.id, objetivo.id, objetivo.id])

    await page.reload()
    await page.getByRole("button", { name: "Tareas", exact: true }).click()
    const grupoObjetivo = page.locator(".objetivo-grupo").filter({ has: page.getByRole("heading", { name: "Proyecto personal actualizado" }) })
    const filaPadre = grupoObjetivo.locator(".lista-tareas > .tarea-nodo").filter({ has: page.getByText("Terminar historial", { exact: true }) })
    const filaHija = filaPadre.locator(":scope > .tareas-hijas > .tarea-nodo").filter({ has: page.getByText("Editar registros", { exact: true }) })
    await expect(filaHija.locator(":scope > .tareas-hijas")).toContainText("Revisar borrado")
    await filaPadre.getByRole("button", { name: "Ocultar subtareas" }).first().click()
    await expect(filaPadre.locator(":scope > .tareas-hijas")).toHaveCount(0)
    await filaPadre.getByRole("button", { name: /Mostrar 1 subtareas/ }).click()
    await expect(filaHija).toBeVisible()
})

test("confirma completar toda la rama o dejar las subtareas pendientes al cancelar el padre", async ({ page }) => {
    await page.goto("/")
    await page.getByRole("button", { name: "Tareas", exact: true }).click()
    await page.getByRole("button", { name: "Crear objetivo" }).click()
    await page.getByLabel("Nombre del objetivo").fill("Objetivo de prueba")
    await page.getByRole("button", { name: "Guardar objetivo" }).click()
    const objetivo = (await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)).find(item => item.tipo === "objetivo")

    await page.getByRole("button", { name: "Crear tarea" }).click()
    await page.getByLabel("Nombre", { exact: true }).fill("Tarea padre")
    await page.getByLabel("Dentro de").selectOption(objetivo.id)
    await page.getByRole("button", { name: "Guardar tarea" }).click()
    let guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    const padre = guardadas.find(item => item.nombre === "Tarea padre")

    await page.getByRole("button", { name: "Crear tarea" }).click()
    await page.getByLabel("Nombre", { exact: true }).fill("Tarea hija")
    await page.getByLabel("Destino").selectOption("focus")
    await page.getByLabel("Dentro de").selectOption(padre.id)
    await page.getByRole("button", { name: "Guardar tarea" }).click()
    guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    const hija = guardadas.find(item => item.nombre === "Tarea hija")

    const filaPadre = page.getByRole("listitem").filter({ has: page.getByText("Tarea padre", { exact: true }) }).first()
    await filaPadre.getByLabel("Estado de Tarea padre").selectOption("Completada")
    await page.getByRole("dialog").getByRole("button", { name: "Completar toda la rama" }).click()
    guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    expect(guardadas.find(item => item.id === padre.id).estado).toBe("Completada")
    expect(guardadas.find(item => item.id === hija.id)).toMatchObject({ estado: "Completada", ordenFocus: null, padreId: padre.id })

    await page.getByRole("button", { name: "Crear tarea" }).click()
    await page.getByLabel("Nombre", { exact: true }).fill("Cancelar solo")
    await page.getByLabel("Dentro de").selectOption(objetivo.id)
    await page.getByRole("button", { name: "Guardar tarea" }).click()
    guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    const padreCancelacion = guardadas.find(item => item.nombre === "Cancelar solo")
    await page.getByRole("button", { name: "Crear tarea" }).click()
    await page.getByLabel("Nombre", { exact: true }).fill("Conservar pendiente")
    await page.getByLabel("Destino").selectOption("focus")
    await page.getByLabel("Dentro de").selectOption(padreCancelacion.id)
    await page.getByRole("button", { name: "Guardar tarea" }).click()
    guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    const hijaPendiente = guardadas.find(item => item.nombre === "Conservar pendiente")
    const filaCancelacion = page.getByRole("listitem").filter({ has: page.getByText("Cancelar solo", { exact: true }) }).first()
    await filaCancelacion.getByLabel("Estado de Cancelar solo").selectOption("Cancelada")
    await page.getByRole("dialog").getByRole("button", { name: "Cancelar solo este" }).click()
    guardadas = await page.evaluate(clave => JSON.parse(localStorage.getItem(clave)), claveTareas)
    expect(guardadas.find(item => item.id === padreCancelacion.id).estado).toBe("Cancelada")
    expect(guardadas.find(item => item.id === hijaPendiente.id)).toMatchObject({ estado: "Pendiente", destino: "focus", padreId: padreCancelacion.id })
})

test("no crea tareas si los datos guardados están corruptos", async ({ page }) => {
    await page.addInitScript(clave => localStorage.setItem(clave, "{"), claveTareas)
    await page.goto("/")
    await page.getByRole("button", { name: "Tareas", exact: true }).click()
    await expect(page.getByRole("alert")).toContainText("formato JSON válido")
    await expect(page.getByRole("button", { name: "Crear tarea" })).toBeDisabled()
    expect(await page.evaluate(clave => localStorage.getItem(clave), claveTareas)).toBe("{")
})
