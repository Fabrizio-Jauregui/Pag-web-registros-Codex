    await page.mouse.down()
    await page.mouse.move(cajaSegundoMovimiento.x + cajaSegundoMovimiento.width / 2, cajaSegundoMovimiento.y + cajaSegundoMovimiento.height / 2 + 64, { steps: 5 })
