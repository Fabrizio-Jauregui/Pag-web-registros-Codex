function fechaDePrueba() {
    const fecha = new Date()
    fecha.setDate(fecha.getDate() + 2)
    const pad = n => String(n).padStart(2, "0")
    const iso = `${fecha.getFullYear()}-${pad(fecha.getMonth() + 1)}-${pad(fecha.getDate())}`
    return { iso, conHora: (h, m = 0, s = 0) => `${iso}T${pad(h)}:${pad(m)}:${pad(s)}` }
}

function fechaISO(fecha) {
    const pad = n => String(n).padStart(2, "0")
    return `${fecha.getFullYear()}-${pad(fecha.getMonth() + 1)}-${pad(fecha.getDate())}`
}

async function abrirBiblioteca(page) {
    await page.goto("/")
    await page.getByRole("button", { name: "Planificaciones", exact: true }).click()
}

