test("Flujo de usuario: al editar un registro vinculado enfoca el primer campo habilitado", async ({ page }) => {
    const inicio = new Date()
    inicio.setDate(inicio.getDate() - 1)
    inicio.setHours(9, 0, 0, 0)
    const fin = new Date(inicio.getTime() + 30 * 60_000)
    const pad = numero => String(numero).padStart(2, "0")
    const fechaHora = fecha => (
        String(fecha.getFullYear()) + "-" + pad(fecha.getMonth() + 1) + "-"
        + pad(fecha.getDate()) + "T" + pad(fecha.getHours()) + ":" + pad(fecha.getMinutes())
    )

    await page.goto("/")
    await page.getByRole("button", { name: "Eventos", exact: true }).focus()
    await page.keyboard.press("Enter")
    await page.getByRole("button", { name: "Crear evento", exact: true }).focus()
    await page.keyboard.press("Enter")
    await page.getByLabel("Nombre", { exact: true }).fill("QA plantilla accesible")
    await page.getByRole("button", { name: "Guardar evento", exact: true }).focus()
    await page.keyboard.press("Enter")

    await page.getByRole("button", { name: "Calendario", exact: true }).focus()
    await page.keyboard.press("Enter")
    await page.getByLabel("Ir a fecha").fill(fechaHora(inicio).slice(0, 10))
    await page.getByRole("button", { name: "Nuevo registro", exact: true }).focus()
    await page.keyboard.press("Enter")
    const formulario = page.getByRole("form", { name: "Nuevo registro manual" })
    await formulario.getByLabel("Plantilla de evento (opcional)").selectOption({
        label: "QA plantilla accesible"
    })
    await formulario.getByLabel("Inicio").fill(fechaHora(inicio))
    await formulario.getByLabel("Fin", { exact: true }).fill(fechaHora(fin))
    await formulario.getByRole("button", { name: "Crear registro", exact: true }).focus()
    await page.keyboard.press("Enter")

    const grupoRegistrosDia = page.getByRole("region", { name: "Calendario" })
        .getByRole("group", { name: /Registros del/ })
    const bloque = grupoRegistrosDia.getByRole("button", { name: /QA plantilla accesible/ })
    await expect(bloque).toBeVisible()
    await bloque.focus()
    await page.keyboard.press("Enter")
    const detalle = page.getByRole("region", { name: "QA plantilla accesible" })
    await detalle.getByRole("button", { name: "Editar registro", exact: true }).focus()
    await page.keyboard.press("Enter")

    const formularioEdicion = page.getByRole("form", { name: "Editar registro finalizado" })
    await expect(formularioEdicion.getByLabel("Nombre de la actividad")).toBeDisabled()
    await expect(formularioEdicion.getByLabel("Inicio")).toBeFocused()
})

test("Flujo de usuario: identifica el día de cada bloque semanal y el estado expandible del historial", async ({ page }) => {
    const dia = new Date()
    dia.setDate(dia.getDate() - 1)
    const pad = numero => String(numero).padStart(2, "0")
    const fecha = String(dia.getFullYear()) + "-" + pad(dia.getMonth() + 1) + "-" + pad(dia.getDate())

    async function crearRegistro(nombre, inicio, fin) {
        await page.getByLabel("Ir a fecha").fill(fecha)
        await page.getByRole("button", { name: "Nuevo registro", exact: true }).click()
        await page.getByLabel("Nombre de la actividad").fill(nombre)
        await page.getByLabel("Inicio").fill(fecha + "T" + inicio)
        await page.getByLabel("Fin", { exact: true }).fill(fecha + "T" + fin)
        await page.getByRole("button", { name: "Crear registro", exact: true }).click()
    }

    await page.goto("/")
    await crearRegistro("Lectura", "09:00", "09:30")
    await crearRegistro("Escritura", "09:15", "09:45")

    await page.getByRole("button", { name: "Historial", exact: true }).click()
    const historial = page.getByRole("region", { name: "Historial" })
    const lecturaResumen = historial.locator("summary").filter({ hasText: "Lectura" })
    await expect(lecturaResumen).toHaveAttribute("aria-expanded", "false")
    await expect(lecturaResumen).toHaveAttribute("aria-controls", /^detalle-historial-/)
    await lecturaResumen.focus()
    await page.keyboard.press("Space")
    await expect(lecturaResumen).toHaveAttribute("aria-expanded", "true")
    await expect(historial).toContainText("Tiempo efectivo")
    await page.keyboard.press("Enter")
    await expect(lecturaResumen).toHaveAttribute("aria-expanded", "false")

    await page.getByRole("button", { name: "Calendario", exact: true }).click()
    await page.getByRole("button", { name: "Semana", exact: true }).click()
    const tabla = page.getByRole("table", { name: /Semana del.*grilla de horas/ })
    await expect(tabla.getByRole("row")).toHaveCount(25)
    const cabeceraDia = tabla.getByRole("columnheader").nth(1)
    await expect(cabeceraDia).toBeVisible()
    expect(await cabeceraDia.ariaSnapshot()).toContain("Tiempo total registrado")

    const gruposSemana = page.getByRole("group", { name: "Actividades de la semana" })
    const etiquetaDiaEnBloque = new Intl.DateTimeFormat("es-AR", {
        weekday: "long", day: "numeric", month: "long"
    }).format(dia)
    const fechaLarga = new Intl.DateTimeFormat("es-AR", {
        weekday: "long", day: "numeric", month: "long", year: "numeric"
    }).format(dia)
    const grupoDia = gruposSemana.getByRole("group", { name: "Actividades del " + fechaLarga })
    await expect(grupoDia.getByRole("button", {
        name: new RegExp("Lectura, " + etiquetaDiaEnBloque + ", En curso, 09:00 a 09:30")
    })).toBeVisible()
    await expect(grupoDia.getByRole("button", {
        name: new RegExp("Escritura, " + etiquetaDiaEnBloque + ", En curso, 09:15 a 09:45")
    })).toBeVisible()
})


test("Flujo de usuario: los bloques siguen accesibles al acercar el calendario", async ({ page }) => {
    const inicio = new Date()
    inicio.setDate(inicio.getDate() - 1)
    inicio.setHours(9, 0, 0, 0)
    const fin = new Date(inicio.getTime() + 2 * 60_000)
    const pad = numero => String(numero).padStart(2, "0")
    const fechaHora = fecha => (
        String(fecha.getFullYear()) + "-" + pad(fecha.getMonth() + 1) + "-"
        + pad(fecha.getDate()) + "T" + pad(fecha.getHours()) + ":" + pad(fecha.getMinutes())
    )

    await page.goto("/")
    await page.getByLabel("Ir a fecha").fill(fechaHora(inicio).slice(0, 10))
    await page.getByRole("button", { name: "Nuevo registro", exact: true }).click()
    const formulario = page.getByRole("form", { name: "Nuevo registro manual" })
    await formulario.getByLabel("Nombre de la actividad").fill("Detalle accesible")
    await formulario.getByLabel("Inicio").fill(fechaHora(inicio))
    await formulario.getByLabel("Fin", { exact: true }).fill(fechaHora(fin))
    await formulario.getByRole("button", { name: "Crear registro", exact: true }).click()

    const calendario = page.getByRole("region", { name: "Calendario" })
    const bloque = calendario.getByRole("group", { name: /Registros del/ })
        .getByRole("button", { name: /Detalle accesible/ })
    await bloque.click()
    await page.getByRole("button", { name: "Acercar calendario" }).click()

    await expect(page.getByRole("heading", { name: "Calendario" })).toBeVisible()
    await expect(page.locator(".calendario-dia-scroll")).toBeVisible()
    await expect(page.locator(".bloque-detalle-tramo").filter({ hasText: "Detalle accesible" })).toBeVisible()
    await expect(page.getByRole("heading", { name: "Calendario ampliado" })).toHaveCount(0)
})

test("Flujo de usuario: la interfaz se reorganiza sin desbordarse a escala equivalente a 200% y en móvil", async ({ page }) => {
    await page.setViewportSize({ width: 640, height: 900 })
    await page.goto("/")
    await expect(page.getByRole("button", { name: "Nuevo registro", exact: true })).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth))
        .toBeLessThanOrEqual(640)

    await page.setViewportSize({ width: 320, height: 780 })
    await expect(page.getByRole("button", { name: "Eventos", exact: true })).toBeVisible()
    await expect(page.getByRole("button", { name: "Iniciar", exact: true })).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth))
        .toBeLessThanOrEqual(320)
})
