import { expect, test } from "@playwright/test"

test("Flujo de usuario: el tema oscuro resalta solo el control activo de edición directa", async ({ page }) => {
    await page.goto("/")
    const botonEdicion = page.getByRole("button", { name: "Edición directa: desactivada" })
    await botonEdicion.click()
    await expect(page.getByRole("button", { name: "Edición directa: activada" }))
        .toHaveCSS("background-color", "rgb(48, 52, 105)")

    await page.getByRole("button", { name: "Planificar actividad", exact: true }).click()
    const formulario = page.locator(".formulario-plan")
    await expect(formulario.locator(":scope > p").first()).toHaveCSS("background-color", "rgba(0, 0, 0, 0)")
    await expect(formulario.locator("label").first()).toHaveCSS("background-color", "rgba(0, 0, 0, 0)")
    await expect(formulario.locator(".ayuda-horario-plan")).toHaveCSS("background-color", "rgba(0, 0, 0, 0)")
})

test("Flujo de usuario: administra plantillas desde teclado con foco visible y restaurado", async ({ page }) => {
    await page.goto("/")
    await page.getByRole("button", { name: "Eventos", exact: true }).focus()
    await page.keyboard.press("Enter")
    const crear = page.getByRole("button", { name: "Crear evento", exact: true })
    await crear.focus()
    await page.keyboard.press("Enter")

    const formulario = page.getByRole("form", { name: "Nuevo evento" })
    const nombre = page.getByLabel("Nombre", { exact: true })
    await expect(formulario).toBeVisible()
    await expect(nombre).toBeFocused()
    await expect.poll(() => nombre.evaluate(element => getComputedStyle(element).outlineColor))
        .toBe("rgb(129, 140, 248)")
    await page.keyboard.press("Escape")
    await expect(page.getByRole("form", { name: "Nuevo evento" })).toHaveCount(0)
    await expect(crear).toBeFocused()
    await page.keyboard.press("Space")
    await expect(page.getByRole("form", { name: "Nuevo evento" })).toBeVisible()
    await expect(nombre).toBeFocused()
    await page.keyboard.press("Enter")
    await expect(page.getByRole("alert")).toHaveText("El nombre del evento es obligatorio.")
    await expect(nombre).toBeFocused()
    await nombre.fill("QA foco teclado")
    await nombre.press("Enter")
    await expect(page.locator(".evento-fila").filter({ hasText: "QA foco teclado" })).toBeVisible()
    await expect(crear).toBeFocused()

    await page.getByRole("button", { name: "Cambiar a tema claro" }).focus()
    await page.keyboard.press("Space")
    await expect(page.locator("html")).toHaveAttribute("data-tema", "claro")
    await crear.focus()
    await page.keyboard.press("Enter")
    await expect(page.getByRole("form", { name: "Nuevo evento" })).toBeVisible()
    await expect(nombre).toBeFocused()
    await expect.poll(() => nombre.evaluate(element => getComputedStyle(element).outlineColor))
        .toBe("rgb(37, 99, 235)")
    await nombre.fill("QA foco teclado claro")
    await nombre.press("Enter")
    const fila = page.locator(".evento-fila").filter({ hasText: "QA foco teclado claro" })
    await expect(fila).toBeVisible()
    await expect(crear).toBeFocused()

    const editar = fila.getByRole("button", { name: "Editar" })
    await editar.focus()
    await page.keyboard.press("Enter")
    await expect(page.getByRole("form", { name: "Editar evento" })).toBeVisible()
    await expect(nombre).toBeFocused()
    await nombre.fill("Cambios descartados")
    await page.keyboard.press("Escape")
    await expect(page.getByRole("form", { name: "Editar evento" })).toHaveCount(0)
    await expect(page.locator(".evento-fila").filter({ hasText: "QA foco teclado claro" })).toBeVisible()
    await expect(fila.getByRole("button", { name: "Editar" })).toBeFocused()
    await page.keyboard.press("Enter")
    await expect(page.getByRole("form", { name: "Editar evento" })).toBeVisible()
    await expect(nombre).toBeFocused()
    await nombre.fill("QA foco teclado editado")
    await nombre.press("Tab")
    await page.keyboard.press("Tab")
    await expect(page.locator(".formulario-evento").getByLabel("Categoría")).toBeFocused()
    await page.keyboard.press("Tab")
    await expect(page.getByRole("button", { name: "Guardar cambios", exact: true })).toBeFocused()
    await page.keyboard.press("Enter")
    const filaEditada = page.locator(".evento-fila").filter({ hasText: "QA foco teclado editado" })
    await expect(filaEditada).toBeVisible()
    await expect(filaEditada.getByRole("button", { name: "Editar" })).toBeFocused()
})

